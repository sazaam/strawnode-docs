/** @module modgraph
 *  Visual dependency graph for strawnode.
 *
 *  Usage:
 *    require('./strawnode_modules/modgraph');
 *    // or assign to a var and call .render() later:
 *    var mod = require('./strawnode_modules/modgraph');
 *    mod.render();
 *
 *  Reads dependency edges collected by ModuleLoader during
 *  evaluateModule and renders an interactive SVG tree.
 *
 *  Dependencies: none (uses DOM API for SVG rendering). */

/** @private Strip origin + query from a module URL, returning the
 *  path relative to the host root. */
function shortUrl(url) {
	var idx = url.indexOf('://');
	if (idx !== -1) {
		var slash = url.indexOf('/', idx + 3);
		if (slash !== -1) url = url.slice(slash);
	}
	return url.replace(/\?.*$/, '');
}

/** @private Return a short display name for a module URL.
 *  - strawnode_modules/ entries show just the filename
 *  - app files show the path relative to js_root */
function moduleLabel(url) {
	var s = shortUrl(url);
	if (s.indexOf('strawnode_modules/') !== -1) {
		return s.match(/strawnode_modules\/(.+)/)[1];
	}
	var parts = s.split('/');
	return parts[parts.length - 1] || s;
}

/* ── layout constants ─────────────────── */

var NODE_W = 280;
var NODE_H = 28;
var LEVEL_GAP = 40;
var ROW_GAP = 6;

/** Build the SVG dependency graph and append it to a target element. */
exports.render = function render(target) {
	target = target || document.body;

	var graph = require.getGraph();
	var cache = graph.cache;
	var edges = graph.edges;

	/* ── build children map ── */
	var children = {};
	var allMods = {};
	for (var child in edges) {
		var parent = edges[child];
		if (!children[parent]) children[parent] = [];
		children[parent].push(child);
		allMods[parent] = true;
		allMods[child] = true;
	}
	for (var url in cache) {
		allMods[url] = true;
	}

	/* ── find roots ── */
	var isChild = {};
	for (var child in edges) isChild[child] = true;
	var roots = [];
	for (var url in allMods) {
		if (!isChild[url]) roots.push(url);
	}
	if (roots.length === 0) {
		for (var url in allMods) { roots.push(url); break; }
	}

	/* ── layout ── */
	var positions = {};
	var totalHeight = 0;
	var yCursor = 10;

	function layoutNode(url, depth, offsetY) {
		if (positions[url]) return 0;
		var kids = (children[url] || []).slice().sort();
		var myY = offsetY;
		positions[url] = { x: 10 + depth * (NODE_W + LEVEL_GAP), y: myY, depth: depth };
		var childY = myY + NODE_H + ROW_GAP;
		var subHeight = 0;
		for (var i = 0; i < kids.length; i++) {
			var h = layoutNode(kids[i], depth + 1, childY + subHeight);
			subHeight += h;
		}
		var total = Math.max(NODE_H + ROW_GAP, subHeight);
		if (kids.length > 0) {
			positions[url].childMid = childY + subHeight / 2 - NODE_H / 2;
		}
		return total;
	}

	var totalW = 20 + 10 * (NODE_W + LEVEL_GAP);
	for (var r = 0; r < roots.length; r++) {
		var h = layoutNode(roots[r], 0, yCursor);
		yCursor += h + 20;
	}
	totalHeight = yCursor + 10;

	/* ── render SVG ── */
	var ns = 'http://www.w3.org/2000/svg';
	var svg = document.createElementNS(ns, 'svg');
	svg.setAttribute('width', totalW);
	svg.setAttribute('height', totalHeight);
	svg.style.fontFamily = 'monospace';
	svg.style.fontSize = '12px';
	svg.style.background = '#1a1a2e';
	svg.style.borderRadius = '8px';
	svg.style.boxShadow = '0 4px 24px rgba(0,0,0,0.3)';

	for (var child in edges) {
		var parent = edges[child];
		var pPos = positions[parent];
		var cPos = positions[child];
		if (!pPos || !cPos) continue;

		var x1 = pPos.x + NODE_W;
		var y1 = (pPos.childMid !== undefined ? pPos.childMid : pPos.y + NODE_H / 2);
		var x2 = cPos.x;
		var y2 = cPos.y + NODE_H / 2;

		var mx = (x1 + x2) / 2;
		var path = document.createElementNS(ns, 'path');
		path.setAttribute('d', 'M' + x1 + ',' + y1 + ' C' + mx + ',' + y1 + ' ' + mx + ',' + y2 + ' ' + x2 + ',' + y2);
		path.setAttribute('stroke', '#4a4a6a');
		path.setAttribute('stroke-width', '1.5');
		path.setAttribute('fill', 'none');
		svg.appendChild(path);
	}

	for (var url in positions) {
		var pos = positions[url];
		var label = moduleLabel(url);
		var isRoot = roots.indexOf(url) !== -1;
		var isNodeMod = url.indexOf('strawnode_modules/') !== -1;

		var g = document.createElementNS(ns, 'g');

		var rect = document.createElementNS(ns, 'rect');
		rect.setAttribute('x', pos.x);
		rect.setAttribute('y', pos.y);
		rect.setAttribute('width', NODE_W);
		rect.setAttribute('height', NODE_H);
		rect.setAttribute('rx', 4);
		rect.setAttribute('ry', 4);

		if (isRoot) {
			rect.setAttribute('fill', '#e94560');
		} else if (isNodeMod) {
			rect.setAttribute('fill', '#0f3460');
		} else {
			rect.setAttribute('fill', '#16213e');
		}
		rect.setAttribute('stroke', '#533483');
		rect.setAttribute('stroke-width', 1);
		g.appendChild(rect);

		var text = document.createElementNS(ns, 'text');
		text.setAttribute('x', pos.x + 8);
		text.setAttribute('y', pos.y + NODE_H / 2 + 1);
		text.setAttribute('fill', '#e0e0e0');
		text.setAttribute('dominant-baseline', 'middle');
		text.textContent = label;
		g.appendChild(text);

		g.style.cursor = 'pointer';
		g.addEventListener('click', (function (u) {
			return function () {
				console.log('[modgraph] ' + u);
				console.log('  source:', (cache[u] || '(no source)').slice(0, 200));
			};
		})(url));
		g.addEventListener('mouseenter', function () {
			rect.setAttribute('fill', '#533483');
		});
		g.addEventListener('mouseleave', function () {
			rect.setAttribute('fill', isRoot ? '#e94560' : isNodeMod ? '#0f3460' : '#16213e');
		});

		svg.appendChild(g);
	}

	target.appendChild(svg);
	console.log('[modgraph] rendered ' + Object.keys(positions).length + ' modules, ' + Object.keys(edges).length + ' edges');
};

/** Auto-render. Call .render() again later for a refreshed view. */
exports.render();
