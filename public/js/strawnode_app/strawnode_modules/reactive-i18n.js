/*
 *  reactive-i18n — live reactive translations for StrawExpress SPA
 *
 *  Replaces the imperative [i18n] attribute scan on step navigation
 *  with reactive computed + effect bindings that auto-update when
 *  the language switches — no step reload needed.
 *
 *  Init (once at app boot):
 *      ReactiveI18n.init();
 *
 *  Per-step binding (in place of imperative ensureTranslates):
 *      ReactiveI18n.bindContainer(project_zone, { stepId: res.id });
 *
 *  Language switch (intercepts .langchange links when init's
 *  hookLangSwitches option is true):
 *      ReactiveI18n.setLang('ko');
 *      // → calls i18next.changeLanguage(), sets scope.lang(),
 *      //   effects re-apply all translations in-place
 */

;(function () {

	var _el = null;
	var _scope = null;
	var _bound = [];
	var _initialized = false;

	var ReactiveI18n = {

		init: function (opts) {
			if (_initialized) return;
			if (typeof i18next === 'undefined' || typeof Reactive === 'undefined') return;
			_initialized = true;
			opts = opts || {};

			_el = document.getElementById('__ri18n');
			if (!_el) {
				_el = document.createElement('div');
				_el.id = '__ri18n';
				_el.style.display = 'none';
				var frame = document.getElementById('frame');
				(frame || document.body).appendChild(_el);
			}

			_scope = Reactive.enhance(prox.hookup(_el));
			_scope.lang(i18next.language || 'en');

			i18next.on('languageChanged', function (lng) {
				if (_scope) _scope.lang(lng);
			});

			if (opts.hookLangSwitches !== false) {
				var $ = window.jQuery;
				if ($) {
					$(document).on('click', '.langchange', function (e) {
						var href = $(this).attr('href');
						var m = href && href.match(/^#\/(\w{2})\//);
						if (m) {
							e.preventDefault();
							ReactiveI18n.setLang(m[1]);
						}
					});
				}
			}

			return ReactiveI18n;
		},

		bindContainer: function (container, opts) {
			if (!_scope) this.init();
			opts = opts || {};
			var stepId = opts.stepId;
			if (stepId == null || stepId === '') stepId = 0;
			var $ = window.jQuery;
			if (!$) return;

			this.cleanup();

			var translates = $(container).find('[i18n]');
			translates.each(function (i, el) {
				var $el = $(el);
				var attr = $el.attr('i18n');
				if (!attr) return;

				var key, defKey;
				if (/\$$/.test(attr)) {
					key = attr.replace('$', '');
					defKey = key;
				} else {
					key = attr + '_0' + stepId;
					defKey = attr + '_00';
				}

				var hasMarked = !!$el.attr('md');

				var teardown = _scope.effect(function () {
					var _ = _scope.lang();
					var trans = i18next.t(key, i18next.t(defKey));
					if (hasMarked && window.marked) {
						trans = window.marked.marked(trans);
					}
					$el.html(trans);
				});
				_bound.push(teardown);
			});
		},

		setLang: function (lng) {
			if (lng === i18next.language) return;
			document.documentElement.setAttribute('lang', lng);
			i18next.changeLanguage(lng);

			var hash = location.hash.replace(/^#\/[^\/]+(?=\/)/, '#/' + lng);
			if (hash !== location.hash) {
				history.replaceState(null, '', hash);
			}

			var $ = window.jQuery;
			if ($) {
				$('a').not('.langchange').each(function () {
					var $a = $(this);
					var href = $a.attr('href');
					if (href && /^#\/\w{2}\//.test(href)) {
						$a.attr('href', href.replace(/^#\/\w{2}\//, '#/' + lng + '/'));
					}
				});
			}
		},

		cleanup: function () {
			_bound.forEach(function (fn) { try { fn(); } catch (e) {} });
			_bound = [];
		}
	};

	if (typeof module !== 'undefined' && module.exports)
		module.exports = ReactiveI18n;
	window.ReactiveI18n = ReactiveI18n;

})();
