/*
 *  reactive-i18n — live reactive translations for StrawExpress SPA
 *
 *  Init once:  ReactiveI18n.init()              (auto-called on first bindContainer)
 *  Per step:   ReactiveI18n.bindContainer(el, { stepId: id })
 *  Language:   ReactiveI18n.setLang('ko')
 *  Teardown:   ReactiveI18n.cleanup()
 *
 *  Effects use a "dry‑run first" pattern so they track scope.lang()
 *  as a dependency but do NOT update the DOM on their initial run —
 *  textAppear has already animated the text in.  Subsequent lang()
 *  changes fire the effects and update translations in‑place instantly.
 */

;(function () {

	var _el = null;
	var _scope = null;
	var _bound = [];
	var _initialized = false;

	var ReactiveI18n = {

		init: function (opts) {
			if (_initialized) return;
			if (typeof i18next === 'undefined' || typeof Reactive === 'undefined') return;
			_initialized = true;
			opts = opts || {};

			_el = document.getElementById('__ri18n');
			if (!_el) {
				_el = document.createElement('div');
				_el.id = '__ri18n';
				_el.style.display = 'none';
				var frame = document.getElementById('frame');
				(frame || document.body).appendChild(_el);
			}

			_scope = Reactive.enhance(prox.hookup(_el));
			_scope.lang(i18next.language || 'en');

			i18next.on('languageChanged', function (lng) {
				if (_scope) _scope.lang(lng);
			});

			if (opts.hookLangSwitches !== false) {
				var $ = window.jQuery;
				if ($) {
					$(document).on('click', '.langchange', function (e) {
						var href = $(this).attr('href');
						var m = href && href.match(/^#\/(\w{2})\//);
						if (m) {
							e.preventDefault();
							ReactiveI18n.setLang(m[1]);
						}
					});
				}
			}

			return ReactiveI18n;
		},

		bindContainer: function (container, opts) {
			if (!_initialized) this.init();
			opts = opts || {};
			var stepId = opts.stepId;
			if (stepId == null || stepId === '') stepId = 0;
			var $ = window.jQuery;
			if (!$) return;

			this.cleanup();

			var translates = $(container).find('[i18n]');
			if (!translates.size()) return;

			var needsApply = false;

			translates.each(function (i, el) {
				var $el = $(el);
				var attr = $el.attr('i18n');
				if (!attr) return;

				var key, defKey;
				if (/\$$/.test(attr)) {
					key = attr.replace('$', '');
					defKey = key;
				} else {
					key = attr + '_0' + stepId;
					defKey = attr + '_00';
				}

				var hasMarked = !!$el.attr('md');

				var teardown = _scope.effect(function () {
					var _ = _scope.lang();
					if (!needsApply) return;
					var trans = i18next.t(key, i18next.t(defKey));
					if (/^jade::/.test(trans)) return;
					if (hasMarked && window.marked) {
						trans = window.marked.marked(trans);
					}
					$el.html(trans);
				});
				_bound.push(teardown);
			});

			needsApply = true;
		},

		setLang: function (lng) {
			// Rewrite the locale segment of the current hash and navigate.
			// Letting the hash change (instead of history.replaceState) makes the
			// framework's hashchange handler drive the switch: it syncs the
			// AddressChanger locale, calls i18next.changeLanguage, and re-focuses
			// the current step so verify_i18 / ensureTranslates re-run and the
			// visible content actually re-translates.
			var hash = location.hash.replace(/^#\/[^\/]+(?=\/)/, '#/' + lng);
			if (hash === location.hash) return;
			location.hash = hash;
		},

		cleanup: function () {
			_bound.forEach(function (fn) { try { fn(); } catch (e) {} });
			_bound = [];
		}
	};

	if (typeof module !== 'undefined' && module.exports)
		module.exports = ReactiveI18n;
	window.ReactiveI18n = ReactiveI18n;

})();
