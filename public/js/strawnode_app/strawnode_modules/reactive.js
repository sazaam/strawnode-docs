/*
 *  reactive — dependency-tracked computed, watch, and effect for DOMNodeProxy scopes
 *
 *  Usage:
 *      var scope = Reactive.scope('#app');
 *      // or:  Reactive.enhance(prox.hookup('#app'))
 *
 *      scope.computed('double', function () { return scope.count() * 2; });
 *      scope.double()  // → 10  (lazy, auto-tracked)
 *
 *      scope.watch('count', function (v) { console.log('count:', v); });
 *
 *      scope.effect(function () {
 *          document.title = 'Count: ' + scope.count();
 *      });
 */

;(function () {

	var activeWatcher = null;

	function track(prop) {
		if (activeWatcher) activeWatcher.deps.add(prop);
	}

	function Watcher(fn) {
		this.fn = fn;
		this.deps = new Set();
		this.value = undefined;
		this.dirty = true;
		this.key = null;
	}

	Watcher.prototype.run = function () {
		var prev = activeWatcher;
		activeWatcher = this;
		this.deps.clear();
		this.value = this.fn();
		activeWatcher = prev;
		this.dirty = false;
		return this.value;
	};

	var subsMap = new WeakMap();

	function subsFor(node, prop) {
		var m = subsMap.get(node);
		if (!m) { m = {}; subsMap.set(node, m); }
		if (!m[prop]) m[prop] = new Set();
		return m[prop];
	}

	function registerDeps(node, w) {
		w.deps.forEach(function (p) { subsFor(node, p).add(w); });
	}

	var batchDepth = 0;
	var pendingBatch = new Map();

	function notify(node, prop) {
		var m = subsMap.get(node);
		if (!m) return;
		var set = m[prop];
		if (!set) return;

		batchDepth++;

		set.forEach(function (w) {
			if (w.dirty) return;
			w.dirty = true;
		});

		set.forEach(function (w) {
			if (w.key) {
				notify(node, w.key);
			} else if (!pendingBatch.has(w)) {
				pendingBatch.set(w, node);
			}
		});

		if (--batchDepth === 0) {
			pendingBatch.forEach(function (n, w) {
				if (w.dirty) {
					w.run();
					registerDeps(n, w);
				}
			});
			pendingBatch.clear();
		}
	}

	var uid = 0;

	var Reactive = {

		scope: function (root) {
			return this.enhance(prox.hookup(root));
		},

		enhance: function (domScope) {
			if (!domScope) return domScope;
			var node = domScope.__target__;
			if (!node || node.__reactive) return domScope;
			node.__reactive = true;

			var id = '_r_' + (uid++);
			node[id] = { computeds: {}, watches: {} };
			var meta = node[id];

			domScope.on('change', function (e) {
				if (e.property) notify(node, e.property);
			});

			// Return a new Proxy over domScope directly, with added methods.
			var reactive = new Proxy(domScope, {
				get: function (target, prop) {
					if (prop === 'computed')
						return function (key, fn) {
							var w = new Watcher(fn);
							w.key = key;
							meta.computeds[key] = w;
							w.run();
							registerDeps(node, w);
							return reactive;
						};
					if (prop === 'watch')
						return function (key, fn) {
							var prev = target[key] ? target[key]() : undefined;
							target.on('change', function (e) {
								if (e.property === key) {
									var cur = target[key] ? target[key]() : undefined;
									fn(cur, prev);
									prev = cur;
								}
							});
							return reactive;
						};
					if (prop === 'effect')
						return function (fn) {
							var w = new Watcher(fn);
							w.run();
							registerDeps(node, w);
							return function () {
								subsMap.forEach(function (m) {
									for (var p in m) m[p].delete(w);
								});
							};
						};
					if (prop === '__reactive') return true;

					// Computed access
					if (prop in meta.computeds) {
						track(prop);
						var c = meta.computeds[prop];
						if (c.dirty) { c.run(); registerDeps(node, c); }
						return function () { return c.value; };
					}

					// Delegate to DOMNodeProxy (returns getter/setter closures)
					track(prop);
					var _v = Reflect.get(target, prop);
					if (typeof _v === 'function') {
						return function () {
							if (arguments.length === 0) return _v();
							_v.apply(target, arguments);
							return reactive;
						};
					}
					return _v;
				},
				set: function (target, prop, val) {
					if (prop in meta.computeds) return true;
					Reflect.set(target, prop, val);
					return true;
				},
				has: function () { return true; }
			});
			return reactive;
		}
	};

	if (typeof module !== 'undefined' && module.exports)
		module.exports = Reactive;
	window.Reactive = Reactive;

})();
