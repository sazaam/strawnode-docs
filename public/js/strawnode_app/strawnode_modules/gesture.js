
var GestureManager = Type.define({
	pkg: 'gesture',
	domain: Type.appdomain,
	
	statics: {
		swipeVelocityThreshold: .6,
		swipeDistanceThreshold: 140,
		clickDistanceThreshold: 5,
		pinchScaleThreshold: 0.05,
		scrollLockThreshold: 15,

		_registry: {},
		_active: {},

		init: function() {
			if (this._initialized) return;
			if (typeof Express === 'undefined') return this;

			var self = this;
			var orig = Express.app.attachHandler;

			Express.app.attachHandler = function(cond, type, handler, res) {
				var t = type.replace('@', '').toLowerCase();
				var gestureTypes = 'swipe swiperight swipeleft swipeup swipedown drag dragright dragleft dragup dragdown dragstart dragend pinch rotate tap'.split(' ');
				if (gestureTypes.indexOf(t) !== -1) {
					if (cond) self.register(res, type.replace('@', ''), handler);
					else self.unregister(res, type.replace('@', ''), handler);
					return;
				}
				return orig.apply(this, arguments);
			};

			this._initialized = true;
			return this;
		},

		listen: function(res, handlers) {
			for (var type in handlers) {
				if (handlers.hasOwnProperty(type)) {
					this.register(res, type, handlers[type]);
				}
			}
			this._unbind(res);
			this._bind(res);
			return this;
		},

		register: function(res, type, handler) {
			var path = res.path || res.id || '';
			if (!this._registry[path]) {
				this._registry[path] = { _res: res };
				var self = this;
				res.bind('focusIn', function(e) { self._bind(e.target); });
				res.bind('focusOut', function(e) { self._unbind(e.target); });
			}
			this._registry[path][type] = handler;
			return this;
		},

		unregister: function(res, type, handler) {
			var path = res.path || res.id || '';
			if (this._registry[path]) {
				delete this._registry[path][type];
			}
			return this;
		},

		config: function(opts) {
			if (opts.swipeVelocityThreshold !== undefined) this.swipeVelocityThreshold = opts.swipeVelocityThreshold;
			if (opts.swipeDistanceThreshold !== undefined) this.swipeDistanceThreshold = opts.swipeDistanceThreshold;
			if (opts.clickDistanceThreshold !== undefined) this.clickDistanceThreshold = opts.clickDistanceThreshold;
			if (opts.pinchScaleThreshold !== undefined) this.pinchScaleThreshold = opts.pinchScaleThreshold;
			if (opts.scrollLockThreshold !== undefined) this.scrollLockThreshold = opts.scrollLockThreshold;
			return this;
		},

		_bind: function(res) {
			this._unbindAll();
			var path = res.path || res.id || '';
			if (this._active[path]) return;

			var el = this._resolveElement(res);
			if (!el) return;

			var isWindow = el === window, scrollChildrenArr = [];
			if (isWindow) {
				document.documentElement.style.touchAction = 'none';
				this._active[path] = {
					el: el, res: res, pointers: {}, scrollChildren: scrollChildrenArr
				};
			} else {
				el.style.touchAction = 'none';
				var scrollChildren = el.querySelectorAll('[data-gesture-scroll]');
				var i = 0, child, axis;
				while (i < scrollChildren.length) {
					child = scrollChildren[i];
					axis = child.getAttribute('data-gesture-scroll');
					if (axis === 'y') child.style.touchAction = 'pan-y';
					else if (axis === 'x') child.style.touchAction = 'pan-x';
					else child.style.touchAction = 'auto';
					scrollChildrenArr.push(child);
					i++;
				}
				this._active[path] = {
					el: el, res: res, pointers: {}, scrollChildren: scrollChildrenArr
				};
			}

			var self = this;
			this._active[path]._onDown = function(e) { self._onPointerDown(e, path); };
			el.addEventListener('pointerdown', this._active[path]._onDown, true);
		},

		_unbind: function(res) {
			var path = res.path || res.id || '';
			var active = this._active[path];
			if (!active) return;

			active.el.removeEventListener('pointerdown', active._onDown, true);
			if (active._onMove) window.removeEventListener('pointermove', active._onMove);
			if (active._onUp) window.removeEventListener('pointerup', active._onUp);
			if (active._onCancel) window.removeEventListener('pointercancel', active._onCancel);

			if (active.el !== window) {
				active.el.style.touchAction = '';
				var si = 0, sc;
				while (si < active.scrollChildren.length) {
					sc = active.scrollChildren[si];
					sc.style.touchAction = '';
					si++;
				}
			} else {
				document.documentElement.style.touchAction = '';
			}

			delete this._active[path];
		},

		_unbindAll: function() {
			for (var path in this._active) {
				if (this._active.hasOwnProperty(path)) {
					this._unbind(this._active[path].res);
				}
			}
		},

		_resolveElement: function(res) {
			if (res.userData && res.userData.gestureEl) {
				var gel = res.userData.gestureEl;
				return typeof gel === 'string' ? $(gel).get(0) : (gel instanceof $ ? gel.get(0) : gel);
			}
			return window;
		},

		_onPointerDown: function(e, path) {
			var active = GestureManager._active[path];
			if (!active) return;

			if (e.pointerType === 'mouse' && e.button !== 0) return;

			var isScrollChild = false;
			var si = 0;
			while (si < active.scrollChildren.length) {
				if (active.scrollChildren[si].contains(e.target)) {
					isScrollChild = true;
					break;
				}
				si++;
			}
			active._isScrollChild = isScrollChild;

			if (!isScrollChild) e.preventDefault();

			if (isScrollChild) {
				active._initialScrollTops = [];
				var si = 0;
				while (si < active.scrollChildren.length) {
					active._initialScrollTops.push(active.scrollChildren[si].scrollTop);
					si++;
				}
			}

			var pointer = {
				id: e.pointerId,
				startX: e.clientX,
				startY: e.clientY,
				startTime: e.timeStamp || performance.now(),
				currentX: e.clientX,
				currentY: e.clientY
			};
			active.pointers[e.pointerId] = pointer;

			var ptrCount = 0, k;
			for (k in active.pointers) { if (active.pointers.hasOwnProperty(k)) ptrCount++; }

			if (ptrCount === 1) {
				var self = GestureManager;
				active._onMove = function(ev) { self._onPointerMove(ev, path); };
				active._onUp = function(ev) { self._onPointerUp(ev, path); };
				active._onCancel = function(ev) { self._onPointerCancel(ev, path); };
				window.addEventListener('pointermove', active._onMove);
				window.addEventListener('pointerup', active._onUp);
				window.addEventListener('pointercancel', active._onCancel);

				if (!isScrollChild) {
					GestureManager._dispatch(active, 'dragstart', {
						type: 'dragstart',
						pointer: pointer,
						sourceEvent: e
					});
				}
			} else if (ptrCount === 2) {
				GestureManager._initMultiTouch(active);
			}
		},

		_onPointerMove: function(e, path) {
			var active = GestureManager._active[path];
			if (!active) return;

			var pointer = active.pointers[e.pointerId];
			if (!pointer) return;

			pointer.currentX = e.clientX;
			pointer.currentY = e.clientY;

			var ptrCount = 0, k;
			for (k in active.pointers) { if (active.pointers.hasOwnProperty(k)) ptrCount++; }

			if (ptrCount === 1) {
				var deltaX = e.clientX - pointer.startX;
				var deltaY = e.clientY - pointer.startY;
				var absX = deltaX < 0 ? -deltaX : deltaX;
				var absY = deltaY < 0 ? -deltaY : deltaY;

				if (active._isScrollChild && absY > absX && absY > GestureManager.scrollLockThreshold) {
					return;
				}

				var direction = absX > absY ? (deltaX > 0 ? 'right' : 'left') : (deltaY > 0 ? 'down' : 'up');
				var w = active.el === window ? (window.innerWidth || 1) : (active.el.clientWidth || 1);
				var h = active.el === window ? (window.innerHeight || 1) : (active.el.clientHeight || 1);

				GestureManager._dispatch(active, 'drag', {
					type: 'drag',
					deltaX: deltaX,
					deltaY: deltaY,
					direction: direction,
					percentX: (deltaX / w) * 100,
					percentY: (deltaY / h) * 100,
					pointer: pointer,
					sourceEvent: e
				});
			} else if (ptrCount === 2) {
				GestureManager._handleMultiTouch(active, e);
			}
		},

		_cancelTracking: function(active, pointerId) {
			delete active.pointers[pointerId];
			var remaining = 0, k;
			for (k in active.pointers) { if (active.pointers.hasOwnProperty(k)) remaining++; }
			if (remaining === 0) {
				if (active._onMove) window.removeEventListener('pointermove', active._onMove);
				if (active._onUp) window.removeEventListener('pointerup', active._onUp);
				if (active._onCancel) window.removeEventListener('pointercancel', active._onCancel);
				active._onMove = null;
				active._onUp = null;
				active._onCancel = null;
				active._pinchState = null;
			}
		},

		_onPointerUp: function(e, path) {
			var active = GestureManager._active[path];
			if (!active) return;

			var pointer = active.pointers[e.pointerId];
			if (!pointer) return;

			delete active.pointers[e.pointerId];

			var endTime = e.timeStamp || performance.now();
			var timeTaken = endTime - pointer.startTime;

			// Use last known position from pointermove if end event gives (0,0)
			var endX = (e.clientX === 0 && e.clientY === 0) ? pointer.currentX : e.clientX;
			var endY = (e.clientY === 0 && e.clientX === 0) ? pointer.currentY : e.clientY;

			var distanceX = endX - pointer.startX;
			var distanceY = endY - pointer.startY;
			var absDistanceX = distanceX < 0 ? -distanceX : distanceX;
			var absDistanceY = distanceY < 0 ? -distanceY : distanceY;
			var velocityX = absDistanceX / (timeTaken || 1);
			var velocityY = absDistanceY / (timeTaken || 1);

			// trace('END e.type='+e.type+' isScroll='+active._isScrollChild+' path='+path+ ' start=('+pointer.startX.toFixed(0)+','+pointer.startY.toFixed(0)+') end=('+endX.toFixed(0)+','+endY.toFixed(0)+') raw=('+e.clientX.toFixed(0)+','+e.clientY.toFixed(0)+') current=('+pointer.currentX.toFixed(0)+','+pointer.currentY.toFixed(0)+') delta=('+distanceX.toFixed(0)+','+distanceY.toFixed(0)+') abs=('+absDistanceX.toFixed(0)+','+absDistanceY.toFixed(0)+') vel=('+velocityX.toFixed(3)+','+velocityY.toFixed(3)+') ms='+timeTaken.toFixed(0));

			// In scroll zones: swipe decision uses scroll distance + finger velocity
			if (active._isScrollChild && absDistanceY > absDistanceX) {
				var si = 0;
				var maxScrollDelta = 0;
				while (si < active.scrollChildren.length) {
					var delta = Math.abs(active.scrollChildren[si].scrollTop - (active._initialScrollTops ? active._initialScrollTops[si] : 0));
					if (delta > maxScrollDelta) maxScrollDelta = delta;
					si++;
				}
				if (maxScrollDelta >= GestureManager.swipeDistanceThreshold && velocityY >= GestureManager.swipeVelocityThreshold) {
					GestureManager._preventNextClick(e);
					GestureManager._dispatch(active, 'swipe', {
						type: 'swipe',
						direction: distanceY > 0 ? 'down' : 'up',
						velocityX: velocityX,
						velocityY: velocityY,
						distanceX: distanceX,
						distanceY: distanceY,
						timeTaken: timeTaken,
						pointer: pointer,
						sourceEvent: e
					});
				}
				GestureManager._cancelTracking(active, e.pointerId);
				return;
			}

			if (timeTaken < 500 && absDistanceX <= GestureManager.clickDistanceThreshold && absDistanceY <= GestureManager.clickDistanceThreshold) {
				// trace('CLASSIFY tap');
				GestureManager._dispatch(active, 'tap', {
					type: 'tap',
					pointer: pointer,
					sourceEvent: e
				});
			} else {
				var dominantIsX = absDistanceX > absDistanceY;
				// trace('CLASSIFY dominant='+(dominantIsX?'X':'Y')+' threshX='+velocityX.toFixed(3)+'>='+GestureManager.swipeVelocityThreshold+' && '+absDistanceX.toFixed(0)+'>='+GestureManager.swipeDistanceThreshold+' | threshY='+velocityY.toFixed(3)+'>='+GestureManager.swipeVelocityThreshold+' && '+absDistanceY.toFixed(0)+'>='+GestureManager.swipeDistanceThreshold);
				var isSwipe = false;
				var direction = null;

				if (dominantIsX) {
					if (velocityX >= GestureManager.swipeVelocityThreshold && absDistanceX >= GestureManager.swipeDistanceThreshold) {
						isSwipe = true;
						direction = distanceX > 0 ? 'right' : 'left';
					}
				} else {
					if (velocityY >= GestureManager.swipeVelocityThreshold && absDistanceY >= GestureManager.swipeDistanceThreshold) {
						isSwipe = true;
						direction = distanceY > 0 ? 'down' : 'up';
					}
				}

				if (isSwipe) {
					// trace('CLASSIFY swipe '+direction);
					GestureManager._preventNextClick(e);
					GestureManager._dispatch(active, 'swipe', {
						type: 'swipe',
						direction: direction,
						velocityX: velocityX,
						velocityY: velocityY,
						distanceX: distanceX,
						distanceY: distanceY,
						timeTaken: timeTaken,
						pointer: pointer,
						sourceEvent: e
					});
				} else {
					// trace('CLASSIFY dragend (threshold not met)');
					GestureManager._preventNextClick(e);
					GestureManager._dispatch(active, 'dragend', {
						type: 'dragend',
						distanceX: distanceX,
						distanceY: distanceY,
						endX: e.clientX,
						endY: e.clientY,
						pointer: pointer,
						sourceEvent: e
					});
				}
			}

			GestureManager._cancelTracking(active, e.pointerId);
		},

		_onPointerCancel: function(e, path) {
			GestureManager._onPointerUp(e, path);
		},

		_dispatch: function(active, gestureType, data) {
			var path = active.res.path || active.res.id || '';
			var registry = GestureManager._registry[path];
			if (!registry) return;

			var handler = registry[gestureType];
			if (handler) handler(data);

			if (data && data.direction) {
				var dir = data.direction;
				var specificType = gestureType + dir.charAt(0).toUpperCase() + dir.slice(1);
				var specific = registry[specificType];
				if (specific) specific(data);
			}
		},

		_preventNextClick: function(e) {
			var target = e.target;
			var handler = function(ev) {
				if (ev.target === target || target.contains(ev.target)) {
					ev.preventDefault();
					ev.stopPropagation();
				}
				window.removeEventListener('click', handler, true);
			};
			window.addEventListener('click', handler, true);
		},

		_initMultiTouch: function(active) {
			var pArray = [];
			var k;
			for (k in active.pointers) {
				if (active.pointers.hasOwnProperty(k)) pArray.push(active.pointers[k]);
			}
			if (pArray.length < 2) return;
			active._pinchState = {
				startDist: GestureManager._getDistance(pArray[0], pArray[1]),
				startAngle: GestureManager._getAngle(pArray[0], pArray[1])
			};
		},

		_handleMultiTouch: function(active, e) {
			if (!active._pinchState) return;
			var pArray = [];
			var k;
			for (k in active.pointers) {
				if (active.pointers.hasOwnProperty(k)) pArray.push(active.pointers[k]);
			}
			if (pArray.length < 2) return;

			var dist = GestureManager._getDistance(pArray[0], pArray[1]);
			var angle = GestureManager._getAngle(pArray[0], pArray[1]);
			var state = active._pinchState;

			var scale = dist / state.startDist;
			var rotation = angle - state.startAngle;

			if ((scale - 1) > GestureManager.pinchScaleThreshold || (1 - scale) > GestureManager.pinchScaleThreshold) {
				GestureManager._dispatch(active, 'pinch', {
					type: 'pinch',
					scale: scale,
					sourceEvent: e
				});
			}

			if ((rotation > 1.5) || (rotation < -1.5)) {
				GestureManager._dispatch(active, 'rotate', {
					type: 'rotate',
					rotation: rotation,
					sourceEvent: e
				});
			}
		},

		_getDistance: function(p1, p2) {
			var dx = p1.currentX - p2.currentX;
			var dy = p1.currentY - p2.currentY;
			return Math.sqrt(dx * dx + dy * dy);
		},

		_getAngle: function(p1, p2) {
			return Math.atan2(p2.currentY - p1.currentY, p2.currentX - p1.currentX) * 180 / Math.PI;
		}
	}
});

GestureManager.init();

module.exports = GestureManager;
