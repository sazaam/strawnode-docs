/** @namespace Unit
 *  Lightweight test framework for strawnode. Supports sync and async tests
 *  (done-callback and Promise/thenable), nested suites, setup/teardown,
 *  and deferred summary that waits for all pending async work to settle.
 *
 *  Async protocol (inspired by strawexpress Command/CommandQueue):
 *    - Test function declares >= 1 parameter → receives `done(err?)` callback
 *    - Test function returns a thenable → runner awaits resolution
 *    - Otherwise → treated as sync, return value traced
 *    - 5-second timeout per async test, with `settled` guard against
 *      double-advancement (race between done, timeout, and thenable)
 *
 *  Suite orchestration:
 *    - Each Unit.TestCase() increments an internal _pending counter
 *    - Unit.summary() defers when _pending > 0, fires when counter hits 0
 *    - Nested suites use an onSuiteDone callback so the parent chain waits */
var Unit = window['Unit'] = {

	tab: '',
	_pass: 0,
	_fail: 0,
	_errors: [],
	_pending: 0,
	_summaryPending: false,
	ASYNC_TIMEOUT: 5000,

	/** Reset all counters and error state between runs. */
	reset: function() {
		this._pass = 0;
		this._fail = 0;
		this._errors = [];
		this._pending = 0;
		this._summaryPending = false;
	},

	/** @private Print the final summary banner. Called by summary()
	 *  either immediately (all sync) or when _pending reaches 0. */
	_fireSummary: function() {
		this._summaryPending = false;
		var total = this._pass + this._fail;
		if (total === 0) {
			trace('──────────────────────────────');
			trace('No tests ran');
			trace('──────────────────────────────');
			return;
		}
		var ok = this._fail === 0;
		trace('──────────────────────────────');
		trace((ok ? '✓  ALL PASSED' : '✗  FAILURES DETECTED') + '  —  ' + this._pass + '/' + total + ' passed');
		if (this._errors.length) {
			trace('');
			trace('Failures:');
			for (var i = 0; i < this._errors.length; i++) {
				trace('  ' + (i + 1) + '. ' + this._errors[i]);
			}
		}
		trace('──────────────────────────────');
	},

	/** Print the summary banner. If async tests are still running,
	 *  defers until they complete. Call at module level after all
	 *  Unit.TestCase() registrations — no need to await. */
	summary: function() {
		if (this._pending > 0) {
			this._summaryPending = true;
			return;
		}
		this._fireSummary();
	},

	/** @private Record a single assertion result.
	 *  @param {boolean} ok       Pass / fail
	 *  @param {string}  msg      Assertion label
	 *  @param {*}       [expected]  Expected value (shown on failure)
	 *  @param {*}       [actual]    Actual value (shown on failure)
	 *  @return {boolean} The ok value, for chaining */
	_report: function(ok, msg, expected, actual) {
		trace(Unit.tab + (ok ? '✓  ' : '✗  ') + msg);
		if (!ok) {
			var detail = msg;
			if (arguments.length > 2) {
				detail += '  (expected: ' + expected + ', actual: ' + actual + ')';
			}
			Unit._errors.push(detail);
		}
		Unit._pass += ok ? 1 : 0;
		Unit._fail += ok ? 0 : 1;
		return ok;
	},

	/* ── helpers ───────────────────────────────── */

	/** @private Resolve Type.is with framework fallback. */
	_isType: function() {
		return (window.Type && Type.is) || function(inst, def) { return inst instanceof def; };
	},

	/** @private Resolve Type.of with framework fallback. */
	_ofType: function() {
		return (window.Type && Type.of) || function(inst, t) {
			if (t === undefined) return typeof inst;
			return typeof inst === t;
		};
	},

	/** @namespace Unit.Assertions Collection of assertion methods.
	 *  Every assertion returns a boolean (pass/fail) for chaining.
	 *  Failures are automatically traced and counted. */
	Assertions: {

		/* ── truth / equality ─────────────────── */

		/** Assert that `value` is truthy.
		 *  @param {string} msg   Description
		 *  @param {*}      value Test value
		 *  @return {boolean} */
		assert: function(msg, value) {
			return Unit._report(!!value, msg);
		},

		/** Assert that `value === true`.
		 *  @param {string} msg   Description
		 *  @param {*}      value Test value
		 *  @return {boolean} */
		assertTrue: function(msg, value) {
			return Unit._report(value === true, msg, true, value);
		},

		/** Assert that `value === false`.
		 *  @param {string} msg   Description
		 *  @param {*}      value Test value
		 *  @return {boolean} */
		assertFalse: function(msg, value) {
			return Unit._report(value === false, msg, false, value);
		},

		/** Loose equality (==).
		 *  @param {string} msg      Description
		 *  @param {*}      expected Expected value
		 *  @param {*}      actual   Actual value
		 *  @return {boolean} */
		assertEquals: function(msg, expected, actual) {
			return Unit._report(expected == actual, msg, expected, actual);
		},

		/** Loose inequality (!=).
		 *  @param {string} msg      Description
		 *  @param {*}      expected Expected value
		 *  @param {*}      actual   Actual value
		 *  @return {boolean} */
		assertNotEquals: function(msg, expected, actual) {
			return Unit._report(expected != actual, msg, expected, actual);
		},

		/** Strict equality (===).
		 *  @param {string} msg      Description
		 *  @param {*}      expected Expected value
		 *  @param {*}      actual   Actual value
		 *  @return {boolean} */
		assertSame: function(msg, expected, actual) {
			return Unit._report(expected === actual, msg, expected, actual);
		},

		/** Strict inequality (!==).
		 *  @param {string} msg      Description
		 *  @param {*}      expected Expected value
		 *  @param {*}      actual   Actual value
		 *  @return {boolean} */
		assertNotSame: function(msg, expected, actual) {
			return Unit._report(expected !== actual, msg, expected, actual);
		},

		/* ── null / undefined ─────────────────── */

		/** Assert `value === null`.
		 *  @param {string} msg   Description
		 *  @param {*}      value Test value
		 *  @return {boolean} */
		assertNull: function(msg, value) {
			return Unit._report(value === null, msg, null, value);
		},

		/** Assert `value !== null`.
		 *  @param {string} msg   Description
		 *  @param {*}      value Test value
		 *  @return {boolean} */
		assertNotNull: function(msg, value) {
			return Unit._report(value !== null, msg, 'not null', value);
		},

		/** Assert `value === undefined`.
		 *  @param {string} msg   Description
		 *  @param {*}      value Test value
		 *  @return {boolean} */
		assertUndefined: function(msg, value) {
			return Unit._report(value === undefined, msg, undefined, value);
		},

		/** Assert `value !== undefined`.
		 *  @param {string} msg   Description
		 *  @param {*}      value Test value
		 *  @return {boolean} */
		assertNotUndefined: function(msg, value) {
			return Unit._report(value !== undefined, msg, 'defined', value);
		},

		/* ── numeric ──────────────────────────── */

		/** Assert that `value` is NaN (uses isNaN after type guard).
		 *  @param {string} msg   Description
		 *  @param {*}      value Test value
		 *  @return {boolean} */
		assertNaN: function(msg, value) {
			var ok = typeof value === 'number' && isNaN(value);
			return Unit._report(ok, msg, 'NaN', value);
		},

		/** Assert that `value` is NOT NaN. Non-number types pass.
		 *  @param {string} msg   Description
		 *  @param {*}      value Test value
		 *  @return {boolean} */
		assertNotNaN: function(msg, value) {
			var ok = !(typeof value === 'number' && isNaN(value));
			return Unit._report(ok, msg, 'not NaN', value);
		},

		/** Assert typeof `value === 'number'` (delegates to Type.of if available).
		 *  @param {string} msg   Description
		 *  @param {*}      value Test value
		 *  @return {boolean} */
		assertNumber: function(msg, value) {
			var T = Unit._ofType();
			return Unit._report(T(value, 'number'), msg, 'number', typeof value);
		},

		/** Assert `value` is a finite integer.
		 *  @param {string} msg   Description
		 *  @param {*}      value Test value
		 *  @return {boolean} */
		assertInt: function(msg, value) {
			var ok = typeof value === 'number' && isFinite(value) && value % 1 === 0;
			return Unit._report(ok, msg, 'integer', value);
		},

		/** Assert `value` is a finite float (non-integer number).
		 *  Infinity and NaN fail.
		 *  @param {string} msg   Description
		 *  @param {*}      value Test value
		 *  @return {boolean} */
		assertFloat: function(msg, value) {
			var ok = typeof value === 'number' && isFinite(value) && value % 1 !== 0;
			return Unit._report(ok, msg, 'float', value);
		},

		/* ── types ────────────────────────────── */

		/** Assert typeof matches `type` (delegates to Type.of if available).
		 *  @param {string} msg    Description
		 *  @param {string} type   Expected typeof string
		 *  @param {*}      object Test value
		 *  @return {boolean} */
		assertTypeOf: function(msg, type, object) {
			var T = Unit._ofType();
			return Unit._report(T(object, type), msg, type, typeof object);
		},

		/** Assert typeof `value === 'boolean'`.
		 *  @param {string} msg   Description
		 *  @param {*}      value Test value
		 *  @return {boolean} */
		assertBoolean: function(msg, value) {
			var T = Unit._ofType();
			return Unit._report(T(value, 'boolean'), msg, 'boolean', typeof value);
		},

		/** Assert typeof `value === 'function'`.
		 *  @param {string} msg   Description
		 *  @param {*}      value Test value
		 *  @return {boolean} */
		assertFunction: function(msg, value) {
			var T = Unit._ofType();
			return Unit._report(T(value, 'function'), msg, 'function', typeof value);
		},

		/** Assert typeof `value === 'string'`.
		 *  @param {string} msg   Description
		 *  @param {*}      value Test value
		 *  @return {boolean} */
		assertString: function(msg, value) {
			var T = Unit._ofType();
			return Unit._report(T(value, 'string'), msg, 'string', typeof value);
		},

		/** Assert `value` is a non-null object.
		 *  @param {string} msg   Description
		 *  @param {*}      value Test value
		 *  @return {boolean} */
		assertObject: function(msg, value) {
			var ok = value !== null && typeof value === 'object';
			return Unit._report(ok, msg, 'object', typeof value);
		},

		/** Assert `value` is an Array (delegates to Type.is / instanceof).
		 *  @param {string} msg   Description
		 *  @param {*}      value Test value
		 *  @return {boolean} */
		assertArray: function(msg, value) {
			var T = Unit._isType();
			var ok = T(value, Array);
			return Unit._report(ok, msg, 'Array', typeof value);
		},

		/* ── instanceof (via Type.is) ─────────── */

		/** Assert `object instanceof constructor`.
		 *  Delegates to Type.is if available for Type.define()-ed classes.
		 *  @param {string} msg         Description
		 *  @param {Function} constructor Expected constructor
		 *  @param {*}      object      Test value
		 *  @return {boolean} */
		assertInstanceOf: function(msg, constructor, object) {
			var T = Unit._isType();
			var ok = T(object, constructor);
			return Unit._report(ok, msg, constructor.name || constructor, typeof object);
		},

		/** Assert `!(object instanceof constructor)`.
		 *  @param {string} msg         Description
		 *  @param {Function} constructor Expected constructor
		 *  @param {*}      object      Test value
		 *  @return {boolean} */
		assertNotInstanceOf: function(msg, constructor, object) {
			var T = Unit._isType();
			var ok = !T(object, constructor);
			return Unit._report(ok, msg, 'not ' + (constructor.name || constructor), typeof object);
		},

		/* ── patterns ─────────────────────────── */

		/** Assert `pattern.test(string)` passes.
		 *  @param {string} msg     Description
		 *  @param {RegExp} pattern Pattern to match
		 *  @param {string} string  Input string
		 *  @return {boolean} */
		assertMatch: function(msg, pattern, string) {
			var ok = pattern.test(string);
			return Unit._report(ok, msg, pattern, string);
		},

		/** Assert `pattern.test(string)` fails.
		 *  @param {string} msg     Description
		 *  @param {RegExp} pattern Pattern to match
		 *  @param {string} string  Input string
		 *  @return {boolean} */
		assertNoMatch: function(msg, pattern, string) {
			var ok = !pattern.test(string);
			return Unit._report(ok, msg, 'no match for ' + pattern, string);
		},

		/* ── exceptions ───────────────────────── */

		/** Assert that `callback` throws. Optionally verify the error
		 *  message contains `type` (substring match).
		 *  @param {string}   msg      Description
		 *  @param {Function} callback Code expected to throw
		 *  @param {string}   [type]   Expected error message substring
		 *  @return {boolean} */
		assertException: function(msg, callback, type) {
			try {
				callback();
			} catch (e) {
				var ok = !type || (e.message && e.message.indexOf(type) !== -1);
				return Unit._report(ok, msg + '  → caught: ' + e.message, type, e.message);
			}
			return Unit._report(false, msg + '  → no exception thrown', 'exception', 'none');
		},

		/** Assert that `callback` does NOT throw.
		 *  @param {string}   msg      Description
		 *  @param {Function} callback Code expected to run cleanly
		 *  @return {boolean} */
		assertNoException: function(msg, callback) {
			try {
				callback();
			} catch (e) {
				return Unit._report(false, msg + '  → threw: ' + e.message, 'no exception', e.message);
			}
			return Unit._report(true, msg);
		},

		/* ── DOM ──────────────────────────────── */

		/** Assert `element.tagName` matches (case-insensitive).
		 *  @param {string} msg      Description
		 *  @param {string} tagName  Expected tag name
		 *  @param {Element} element DOM element
		 *  @return {boolean} */
		assertTagName: function(msg, tagName, element) {
			if (!element || !element.tagName) {
				return Unit._report(false, msg, 'DOM element', element);
			}
			var ok = element.tagName.toLowerCase() === tagName.toLowerCase();
			return Unit._report(ok, msg, tagName, element.tagName);
		},

		/** Assert `element.classList.contains(className)`.
		 *  @param {string} msg       Description
		 *  @param {string} className Expected class
		 *  @param {Element} element  DOM element
		 *  @return {boolean} */
		assertClassName: function(msg, className, element) {
			if (!element || !element.classList) {
				return Unit._report(false, msg, 'DOM element', element);
			}
			var ok = element.classList.contains(className);
			return Unit._report(ok, msg, className, element.className);
		},

		/** Assert `element.getAttribute('id') == id` (loose equality).
		 *  @param {string} msg     Description
		 *  @param {string} id      Expected id
		 *  @param {Element} element DOM element
		 *  @return {boolean} */
		assertElementId: function(msg, id, element) {
			if (!element) {
				return Unit._report(false, msg, 'DOM element', element);
			}
			var ok = element.getAttribute('id') == id;
			return Unit._report(ok, msg, id, element.getAttribute('id'));
		}
	},

	/* ── test runner ───────────────────────────── */

	/** Register and run a test suite. Supports sync, done-callback,
	 *  and Promise/thenable tests, nested suites, and setup/teardown.
	 *
	 *  @param {string}   description Suite name (printed as banner)
	 *  @param {Object}   methods     Test functions keyed by name.
	 *      Special keys:
	 *        setup    — runs before all tests in suite
	 *        tearDown — runs after all tests in suite
	 *        Object value — nested suite (recurses with deeper indent)
	 *  @param {number}   [deep]      Internal nesting depth
	 *  @param {Function} [onSuiteDone] Internal callback when suite completes
	 *
	 *  Test function signatures:
	 *    function()           — sync, return value traced
	 *    function(done)       — async, call done(err?) when finished
	 *    function() { return promise } — async via thenable
	 *
	 *  Async tests have a 5-second timeout (Unit.ASYNC_TIMEOUT).
	 *  If done() is not called and the Promise doesn't settle,
	 *  the test is reported as failed. */
	TestCase: function testCaseRunner(description, methods, deep, onSuiteDone) {
		deep = deep || 0;
		var tab = Unit.tab = new Array(deep + 1).join('\t');
		var self = Unit;

		trace('');
		trace(tab + '═══════════════════════════');
		trace(tab + description.toUpperCase());
		trace(tab + '═══════════════════════════');

		var setupFn, teardownFn;
		var items = [];

		for (var key in methods) {
			if (methods.hasOwnProperty(key)) {
				if (key === 'setup' && typeof methods[key] === 'function') {
					setupFn = methods[key];
				} else if (key === 'tearDown' && typeof methods[key] === 'function') {
					teardownFn = methods[key];
				} else {
					items.push({ name: key, fn: methods[key] });
				}
			}
		}

		self._pending++;

		/** @private Called when the entire suite (including nested) finishes.
		 *  Decrements the global counter and triggers deferred summary. */
		function suiteDone() {
			trace(tab + '───────────────────────────');
			self._pending--;
			if (self._pending === 0 && self._summaryPending)
				self._fireSummary();
			if (onSuiteDone) onSuiteDone();
		}

		/** @private Run setup, supporting thenable returns. */
		function runSetup(cb) {
			if (!setupFn) { cb(); return; }
			var r = setupFn();
			trace(tab + 'setup → ' + r);
			if (r && typeof r.then === 'function') {
				r.then(function() { cb(); });
				return;
			}
			cb();
		}

		/** @private Run teardown, supporting thenable returns. */
		function runTeardown(cb) {
			if (!teardownFn) { cb(); return; }
			var r = teardownFn();
			trace(tab + 'tearDown → ' + r);
			if (r && typeof r.then === 'function') {
				r.then(function() { cb(); });
				return;
			}
			cb();
		}

		/** @private Execute a single test entry and advance the chain.
		 *  Dispatches to sync, done-callback, or thenable path based on
		 *  fn.length and return value inspection. */
		function runTest(entry, cb) {
			trace(tab + entry.name);
			var settled = false;

			if (entry.fn.length >= 1) {
				var tid = setTimeout(function() {
					settled = true;
					self._report(false, entry.name + ' timed out', 'complete', 'timeout');
					cb();
				}, self.ASYNC_TIMEOUT);
				try {
					entry.fn(function(err) {
						if (settled) return;
						settled = true;
						clearTimeout(tid);
						if (err && err !== true) {
							self._report(false, entry.name, 'no error', err.message || String(err));
						} else if (err === true) {
							self._report(false, entry.name, 'pass', 'fail');
						} else {
							trace(tab + '\t✓');
						}
						cb();
					});
				} catch (e) {
					if (settled) return;
					settled = true;
					clearTimeout(tid);
					self._report(false, entry.name + ' threw', 'no error', e.message);
					cb();
				}
				return;
			}

			var result;
			try {
				result = entry.fn();
			} catch (e) {
				self._report(false, entry.name + ' threw', 'no error', e.message);
				cb();
				return;
			}

			if (result && typeof result.then === 'function') {
				result.then(function(val) {
					if (settled) return;
					settled = true;
					trace(tab + '\treturn: ' + val);
					cb();
				}, function(err) {
					if (settled) return;
					settled = true;
					self._report(false, entry.name + ' rejected', 'no error', err.message || String(err));
					cb();
				});
				return;
			}

			trace(tab + '\treturn: ' + result);
			cb();
		}

		/** @private Sequential runner. Processes each item in order,
		 *  waiting for async tests and nested suites to complete before
		 *  advancing. */
		var index = 0;
		function next() {
			if (index >= items.length) {
				runTeardown(suiteDone);
				return;
			}
			var entry = items[index++];

			if (typeof entry.fn === 'function') {
				runTest(entry, next);
			} else if (typeof entry.fn === 'object' && entry.fn !== null) {
				testCaseRunner(entry.name, entry.fn, deep + 1, next);
			} else {
				next();
			}
		}

		runSetup(next);
	}
};

module.exports = Unit;
