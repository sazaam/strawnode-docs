
var KeyboardManager = Type.define({
	pkg: 'keyboard',
	domain: Type.appdomain,

	statics: {
		_registry: {},
		_active: {},

		init: function() {
			if (this._initialized) return;
			if (typeof Express === 'undefined') return this;

			var self = this;
			var orig = Express.app.attachHandler;

			Express.app.attachHandler = function(cond, type, handler, res) {
				var t = type.replace('@', '').toLowerCase();
				if (t === 'keydown' || t.indexOf('keydown ') === 0) {
					if (cond) self.register(res, t, handler);
					else self.unregister(res, t, handler);
					return;
				}
				return orig.apply(this, arguments);
			};

			this._initialized = true;
			return this;
		},

		register: function(res, type, handler) {
			var path = res.path || res.id || '';
			if (!this._registry[path]) {
				this._registry[path] = { _res: res };
				var self = this;
				res.bind('focusIn', function(e) { self._bind(e.target); });
				res.bind('focusOut', function(e) { self._unbind(e.target); });
			}
			this._registry[path][type] = handler;
			return this;
		},

		unregister: function(res, type, handler) {
			var path = res.path || res.id || '';
			if (this._registry[path]) {
				delete this._registry[path][type];
			}
			return this;
		},

		_bind: function(res) {
			this._unbindAll();
			var path = res.path || res.id || '';
			if (this._active[path]) return;

			var self = this;
			var handler = function(e) { self._onKeyDown(e, path); };

			this._active[path] = { res: res, handler: handler };
			window.addEventListener('keydown', handler);
		},

		_unbind: function(res) {
			var path = res.path || res.id || '';
			var active = this._active[path];
			if (!active) return;
			window.removeEventListener('keydown', active.handler);
			delete this._active[path];
		},

		_unbindAll: function() {
			for (var path in this._active) {
				if (this._active.hasOwnProperty(path)) {
					this._unbind(this._active[path].res);
				}
			}
		},

		_onKeyDown: function(e, path) {
			var registry = this._registry[path];
			if (!registry) return;

			// Dispatch scoped handlers first: @keydown .selector
			for (var type in registry) {
				if (type !== '_res' && type.indexOf('keydown ') === 0) {
					var selector = type.slice(8).trim();
					if (selector) {
						var el = document.activeElement;
						if (el && $(el).is(selector)) {
							registry[type]({
								key: e.key,
								code: e.code,
								keyCode: e.keyCode,
								ctrlKey: e.ctrlKey,
								shiftKey: e.shiftKey,
								altKey: e.altKey,
								metaKey: e.metaKey,
								repeat: e.repeat,
								sourceEvent: e,
								target: el,
								preventDefault: function() { e.preventDefault(); }
							});
							return;
						}
					}
				}
			}

			// Dispatch general @keydown
			var general = registry['keydown'];
			if (general) {
				general({
					key: e.key,
					code: e.code,
					keyCode: e.keyCode,
					ctrlKey: e.ctrlKey,
					shiftKey: e.shiftKey,
					altKey: e.altKey,
					metaKey: e.metaKey,
					repeat: e.repeat,
					sourceEvent: e,
					target: e.target,
					preventDefault: function() { e.preventDefault(); }
				});
			}
		}
	}
});

KeyboardManager.init();

module.exports = KeyboardManager;
